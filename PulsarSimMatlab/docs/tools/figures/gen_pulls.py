import numpy as np
from plotsvg import Ax
# Why long runs are judged by pulls at fixed times over many realizations (validation.html #longruns), illustrative: a smoothed
# track's error divided by its stated sigma, modelled as a stationary Gaussian process with unit variance and a correlation time of
# 3 days (squared-exponential), sampled every hour for 14 days. An honest filter: the pulls have unit variance at every time.
# a: eight runs, and their pulls at the four fixed times of the ship runs (days 3, 7, 10, 14).
# b: what each way of judging says over 2000 repetitions: the rms of all hourly pulls of ONE run, against the rms of the
# fixed-time pulls pooled over EIGHT runs (32 pulls).
days = np.arange(0, 14 + 1e-9, 1 / 24); n = days.size; tc = 3.0; fixed = [3, 7, 10, 14]
Cm = np.exp(-((days[:, None] - days[None, :]) / tc)**2) + 1e-9 * np.eye(n)
Lc = np.linalg.cholesky(Cm)
rng = np.random.default_rng(4)
runs = lambda m: (Lc @ rng.standard_normal((n, m))).T
idx = [int(np.argmin(np.abs(days - d))) for d in fixed]
o = []
# a
A = Ax(70, 50, 400, 230, (0, 14), (-3.2, 3.2))
o.append(f'<path class="fillfg" style="opacity:0.12" d="M{A.x0} {float(A.Y(1)):.1f} H{A.x0 + A.w} V{float(A.Y(-1)):.1f} H{A.x0} Z"/>')
for v in (-2, 0, 2):
    o.append(f'<path class="grid" d="M{A.x0} {float(A.Y(v)):.1f} H{A.x0 + A.w}"/>')
o.append(A.frame(xticks=[0, 3, 7, 10, 14], yticks=[-2, -1, 0, 1, 2], xlab='days', ylab='pull: error / stated σ'))
R = runs(8)
for r in R:
    o.append(f'<path class="s1" style="stroke-width:1.2;opacity:0.7" d="{A.path(days, r)}"/>')
for d in fixed:
    o.append(f'<path class="dash" d="M{float(A.X(d)):.1f} {A.y0} V{A.y0 + A.h}"/>')
for r in R:
    for i in idx:
        o.append(f'<circle class="s2f" cx="{float(A.X(days[i])):.1f}" cy="{float(A.Y(r[i])):.1f}" r="3.8"/>')
o.append(f'<text class="sub" x="{A.x0 + A.w}" y="{A.y0 - 8}" text-anchor="end" style="fill:var(--series-2)">pulls at fixed times</text>')
o.append('<text class="ttl" x="70" y="24">a · eight runs of an honest filter</text>')
# b
M = 2000
rms = lambda v: np.sqrt(np.mean(v**2))
one = np.array([rms(runs(1)[0]) for _ in range(M)])
pooled = np.array([rms(runs(8)[:, idx]) for _ in range(M)])
B = Ax(560, 50, 270, 230, (0, 2), (0, 1))
bins = np.linspace(0, 2, 41)
h1, _ = np.histogram(one, bins); h2, _ = np.histogram(pooled, bins)
top = max(h1.max(), h2.max()) * 1.08
B.ylim = (0, top)
for h, cls in ((h1, 's1'), (h2, 's2')):
    xs = np.repeat(bins, 2)[1:-1]; ys = np.repeat(h, 2)
    o.append(f'<path class="{cls}band" d="{B.area(xs, ys)}"/>')
    o.append(f'<path class="{cls}" style="stroke-width:1.5" d="{B.path(xs, ys)}"/>')
o.append(f'<path class="dash" d="M{float(B.X(1)):.1f} {B.y0} V{B.y0 + B.h}"/>')
o.append(B.frame(xticks=[0, 0.5, 1, 1.5, 2], xlab='measured rms of the pulls (truth: 1)', ylab='how often', left=False))
q1 = np.percentile(one, [5, 95]); q2 = np.percentile(pooled, [5, 95])
o.append(f'<text class="sub" x="{float(B.X(1.25)):.1f}" y="{float(B.Y(h1.max() * 0.55)):.1f}" style="fill:var(--series-1)">one run, all pulls</text>')
o.append(f'<text class="sub" x="{float(B.X(1.12)):.1f}" y="{float(B.Y(h2.max() * 0.85)):.1f}" style="fill:var(--series-2)">eight runs, fixed times</text>')
o.append('<text class="ttl" x="560" y="24">b · what each way of judging says</text>')

svg = '''<figure class="scroll">
<svg class="wide" viewBox="0 0 860 330" role="img" aria-label="Pulls of a smoothed track: eight runs whose errors wander slowly over 14 days, sampled at four fixed times; and the spread of the measured pull width from one run alone, much wider than from the fixed-time pulls of eight runs">
  ''' + '\n  '.join(o) + '''
</svg>
<figcaption>Why long runs are judged at fixed times over many runs, illustrated with a filter whose error bars are exactly right. Its
errors, divided by their stated σ, wander slowly: here they stay correlated for about 3 days. a: eight runs over 14 days. One run
stays above or below zero for days, so its hourly pulls are far from independent. The orange dots are the pulls at days 3, 7, 10 and 14,
as in the ship runs. b: the rms of the pulls that each method measures, over 2000 repetitions. From one run's hourly pulls it lands
anywhere between ''' + f'{q1[0]:.2f} and {q1[1]:.2f}' + ''' (90 % of the time), although the truth is 1. From the fixed-time pulls of
eight runs it lands between ''' + f'{q2[0]:.2f} and {q2[1]:.2f}' + '''. Generated by <code>docs/tools/figures/gen_pulls.py</code>.</figcaption>
</figure>'''
open('pulls.svg', 'w').write(svg)
print('one run 5-95%', q1, 'median', np.median(one), '| pooled 5-95%', q2, 'median', np.median(pooled))
