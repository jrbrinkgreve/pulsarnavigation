import numpy as np
from plotsvg import Ax
# Adaptive sub-int length (simulator.html #adaptive), illustrative: adaptiveSubints' rule on sub-ints with a mean SNR of 1.2 each
# (testSimulateFold 12: -25 dB, one turn per sub-int) under scintillation as simulateFold draws it (complex white noise smoothed with a
# Gaussian kernel, F = |g|^2: exponential statistics, intensity correlation exp(-(dt/T)^2), here T = 60 sub-ints). Each sub-int's
# matched-filter statistic at the predicted phase is F s + n with unit noise n; the merged group's T0 = sum / sqrt(count) (equal
# weights); a group closes when T0 reaches 7 (TargetSNR), and the next one starts.
nS = 600; s = 1.2; Tsc = 60.0; target = 7.0
rng = np.random.default_rng(5)
pad = int(4 * Tsc); dT = Tsc / 10
grid = np.arange(-pad, nS + pad, dT)
w = (rng.standard_normal(grid.size) + 1j * rng.standard_normal(grid.size)) / np.sqrt(2)
kk = np.arange(-int(3 * Tsc / dT), int(3 * Tsc / dT) + 1) * dT
kern = np.exp(-kk**2 / (2 * (Tsc / np.sqrt(2))**2)); kern /= np.sqrt(np.sum(kern**2))
g = np.convolve(w, kern, mode='same')
F = np.abs(np.interp(np.arange(nS) + 0.5, grid, g.real) + 1j * np.interp(np.arange(nS) + 0.5, grid, g.imag))**2
x = F * s + rng.standard_normal(nS)
groups, T0trace, cur, start = [], np.zeros(nS), [], 0
for i in range(nS):
    cur.append(x[i]); T0 = np.sum(cur) / np.sqrt(len(cur)); T0trace[i] = T0
    if T0 >= target:
        groups.append((start, i + 1, True)); cur = []; start = i + 1
if cur:
    groups.append((start, nS, False))
o = []
# a: the flux factor
A = Ax(80, 50, 740, 110, (0, nS), (0, max(4.0, F.max() * 1.05)))
for v in (1, 2, 3):
    o.append(f'<path class="grid" d="M{A.x0} {float(A.Y(v)):.1f} H{A.x0 + A.w}"/>')
o.append(A.frame(yticks=[0, 1, 2, 3], ylab='flux factor F'))
o.append(f'<path class="s1band" d="{A.area(np.arange(nS) + 0.5, F)}"/>')
o.append(f'<path class="s1" style="stroke-width:1.4" d="{A.path(np.arange(nS) + 0.5, F)}"/>')
o.append(f'<text class="sub" x="{A.x0 + A.w}" y="{A.y0 - 8}" text-anchor="end">mean 1: the pulsar\'s catalogue flux</text>')
o.append('<text class="ttl" x="80" y="24">a · scintillation: the pulsar fades and brightens</text>')
# b: T0 of the open group, groups closing at 7
B = Ax(80, 230, 740, 140, (0, nS), (-2, 10))
for v in (0, 7):
    o.append(f'<path class="{"dash" if v == 7 else "grid"}" d="M{B.x0} {float(B.Y(v)):.1f} H{B.x0 + B.w}"/>')
o.append(B.frame(xticks=[0, 100, 200, 300, 400, 500, 600], yticks=[0, 7], xlab='sub-int', ylab='T0 of the group being merged'))
for gi, (a, b, done) in enumerate(groups):
    cls = 's2' if gi % 2 else 's1'
    xs = np.arange(a, b) + 1.0
    o.append(f'<path class="{cls}" style="stroke-width:1.4" d="{B.path(np.r_[a, xs], np.r_[0, T0trace[a:b]])}"/>')
    o.append(f'<path class="{cls}" style="stroke-width:6" stroke-linecap="butt" d="M{float(B.X(a)) + 0.5:.1f} {B.y0 + B.h + 0:.1f} H{float(B.X(b)) - 0.5:.1f}">'
             f'<title>group {gi + 1}: {b - a} sub-ints{"" if done else ", below the target"}</title></path>')
o.append(f'<text class="sub" x="{B.x0 + B.w}" y="{float(B.Y(7)) - 6:.1f}" text-anchor="end">target 7: the group closes, a TOA is made</text>')
o.append('<text class="ttl" x="80" y="204">b · merging sub-ints until the SNR reaches 7</text>')
n = np.array([b - a for a, b, d in groups if d]); Fg = np.array([F[a:b].mean() for a, b, d in groups if d])
bright, faint = np.median(n[Fg > 1]), np.median(n[Fg <= 1])

svg = '''<figure class="scroll">
<svg class="wide" viewBox="0 0 860 420" role="img" aria-label="Adaptive sub-ints: the scintillating flux of a pulsar over 600 sub-ints, and the matched-filter statistic of the group being merged, which closes each time it reaches 7; groups are short when the pulsar is bright and long when it is faint">
  ''' + '\n  '.join(o) + '''
</svg>
<figcaption><b>Figure F.2.</b> What <code>adaptiveSubints</code> does, with its rule and <code>simulateFold</code>'s scintillation model, for a pulsar of SNR
1.2 per sub-int on average, as in <code>testSimulateFold</code> 12. (a) Scintillation multiplies the flux by a factor that wanders on a time
scale of 60 sub-ints here. (b) Short sub-ints are added to a group one at a time, and the group's T0 grows; as soon as it reaches 7 the group
closes (bars under the axis). While the pulsar is bright a group needs ''' + f'{bright:.0f}' + ''' sub-ints (median); while it is faint, ''' + f'{faint:.0f}' + '''. Generated by
<code>docs/tools/figures/gen_adaptive.py</code>.</figcaption>
</figure>'''
open('adaptive.svg', 'w').write(svg)
print(len(groups), 'groups; sizes', n, 'bright median', bright, 'faint median', faint, 'F mean', F.mean())
