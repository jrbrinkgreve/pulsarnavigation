import numpy as np
from plotsvg import Ax
# The time scales (localisation.html #time) as offsets from TT, 1972-2030. TAI = TT - 32.184 s (exact); UTC = TAI - (TAI - UTC),
# the leap-second table of IERS Bulletin C (10 s in 1972 ... 37 s since 2017); UT1 stays within 0.9 s of UTC (the code takes
# UT1 = UTC: delayModel's DeltaT = TT - UT1 = 69.184 s); TDB - TT stays within 1.7 ms (delayModel's Einstein term); TCB - TDB =
# L_B (t - T0) with L_B = 1.550519768e-8 and T0 = 1977-01-01 (IAU 2006 resolution B3; TDB0 = -65.5 us left out).
leaps = [(1972.0, 10), (1972.5, 11), (1973, 12), (1974, 13), (1975, 14), (1976, 15), (1977, 16), (1978, 17), (1979, 18), (1980, 19),
         (1981.5, 20), (1982.5, 21), (1983.5, 22), (1985.5, 23), (1988, 24), (1990, 25), (1991, 26), (1992.5, 27), (1993.5, 28),
         (1994.5, 29), (1996, 30), (1997.5, 31), (1999, 32), (2006, 33), (2009, 34), (2012.5, 35), (2015.5, 36), (2017, 37)]
YR = 365.25 * 86400; LB = 1.550519768e-8
x0, x1 = 1972, 2030
A = Ax(90, 40, 600, 250, (x0, x1), (-80, 40))
o = []
for v in (-80, -60, -40, -20, 0, 20, 40):
    o.append(f'<path class="grid" d="M{A.x0} {float(A.Y(v)):.1f} H{A.x0 + A.w}"/>')
o.append(A.frame(xticks=[1980, 1990, 2000, 2010, 2020, 2030], yticks=[-80, -60, -40, -20, 0, 20, 40], ylab='offset from TT [s]',
                 yfmt=lambda v: f'{v:+d}' if v else '0'))
# TT and TDB
o.append(f'<path class="dash" d="M{A.x0} {float(A.Y(0)):.1f} H{A.x0 + A.w}"/>')
# TAI
o.append(f'<path class="s3" d="{A.path([x0, x1], [-32.184, -32.184])}"/>')
# UTC: a staircase
xs, ys = [x0], [-32.184 - 10]
for (y, n) in leaps[1:]:
    xs += [y, y]; ys += [ys[-1], -32.184 - n]
xs.append(x1); ys.append(ys[-1])
o.append(f'<path class="s2" d="{A.path(xs, ys)}"><title>UTC: leap seconds keep it within 0.9 s of the Earth\'s rotation (UT1)</title></path>')
# TCB
tc = np.array([1977, x1]); o.append(f'<path class="s1" d="{A.path(tc, LB * (tc - 1977) * YR)}"/>')
tcb26 = LB * (2026 - 1977) * YR
o.append(f'<circle class="s1f" cx="{float(A.X(2026)):.1f}" cy="{float(A.Y(tcb26)):.1f}" r="4.5"><title>TCB − TDB on 1 January 2026: {tcb26:.1f} s</title></circle>')
lx = A.x0 + A.w + 10
labels = [(LB * (x1 - 1977) * YR, 'TCB: +0.49 s per year', 'var(--series-1)'), (2, 'TT and TDB (within 1.7 ms)', None),
          (-32.184, 'TAI = TT − 32.184 s', 'var(--series-3)'), (-69.184, 'UTC ≈ UT1: TT − 69.184 s', 'var(--series-2)')]
for y, lab, col in labels:
    st = f' style="fill:{col}"' if col else ''
    o.append(f'<text class="sub" x="{lx}" y="{float(A.Y(y)) + 4:.1f}"{st}>{lab}</text>')
o.append(f'<text class="sub" x="{float(A.X(2026)) - 6:.1f}" y="{float(A.Y(tcb26)) - 8:.1f}" text-anchor="end" style="fill:var(--series-1)">{tcb26:.0f} s in 2026</text>')
o.append(f'<text class="sub" x="{float(A.X(1996)):.1f}" y="{float(A.Y(-72)):.1f}" text-anchor="middle" style="fill:var(--series-2)">one step per leap second</text>')

svg = '''<figure class="scroll">
<svg class="wide" viewBox="0 0 900 330" role="img" aria-label="The time scales as offsets from terrestrial time, 1972 to 2030: TAI a constant 32.184 s behind, UTC stepping away with every leap second to 69.184 s behind, TCB drifting ahead by 0.49 s per year to 24 s in 2026, and TDB within 1.7 ms of TT">
  ''' + '\n  '.join(o) + '''
</svg>
<figcaption><b>Figure L.2.</b> The time scales as offsets from terrestrial time TT. TAI is a constant 32.184 s behind TT. UTC falls one second further behind at
every leap second; since 2017 it is 69.184 s behind, the value the code takes for the Earth's rotation. TDB stays within 1.7 ms of TT, so on
this scale it lies on TT's line. TCB runs ahead of TDB by 0.49 s per year since 1977, and in 2026 it is 24 s ahead. Generated by
<code>docs/tools/figures/gen_timesys.py</code>.</figcaption>
</figure>'''
open('timesys.svg', 'w').write(svg)
print('TCB-TDB 2026', tcb26)
