import numpy as np
from plotsvg import Ax
# Why the phase must be predicted (fold.html#prediction #why): B0329+54's profile (runScenario's five Gaussian components at 1410 MHz,
# peak 1) in a 120 s sub-int whose arrival rate is off by the Doppler factor 1e-4 of the Earth's orbit (the page's numbers: 12 ms
# per sub-int). a: a pulse stack, one row every 5 s: with a constant spin rate the pulse walks; with the predictor it stays.
# b: the folded profiles (the average over the sub-int's turns): the walk smears the fold.
P = 0.714519699726; T = 120.0; dop = 1e-4
cB = np.array([[0.159, -11.427, 1.479], [0.439, -1.123, 3.281], [0.585, 0, 1.055], [0.152, 7.719, 2.751], [0.170, 9.482, 0.847]])
amp, cen, fw = cB[:, 0], cB[:, 1] / 360 * P * 1e3, cB[:, 2] * 2 * np.sqrt(2 * np.log(2)) / 360 * P * 1e3   # ms
prof = lambda t: np.sum(amp[:, None] * np.exp(-4 * np.log(2) * (t[None, :] - cen[:, None])**2 / fw[:, None]**2), 0)
tt = np.linspace(-35, 45, 801); pk = prof(tt).max()
p = lambda t: prof(t) / pk
D = dop * T * 1e3                                          # ms of walk per sub-int
rows = np.arange(0, T + 0.1, 5.0)
o = []
for k, (x0, walk, ttl) in enumerate(((80, True, 'a · constant spin rate'), (330, False, 'with the predictor'))):
    A = Ax(x0, 50, 200, 230, (tt[0], tt[-1]), (-8, T + 12))
    for v in (-20, 0, 20, 40):
        o.append(f'<path class="grid" d="M{float(A.X(v)):.1f} {A.y0} V{A.y0 + A.h}"/>')
    for r in rows[::-1]:                                   # back to front: each row hides the rows behind it
        y = p(tt - (D * r / T if walk else 0)) * 10 + r
        o.append(f'<path style="fill:var(--bg)" d="{A.area(tt, y, base=r)}"/>')
        o.append(f'<path class="{"s2" if walk else "s1"}" style="stroke-width:1.3" d="{A.path(tt, y, clip=False)}"/>')
    o.append(A.frame(xticks=[-20, 0, 20, 40], xlab='time in the turn [ms]', yticks=[0, 60, 120] if k == 0 else [],
                     ylab='time in the sub-int [s]' if k == 0 else '', left=(k == 0)))
    o.append(f'<text class="ttl" x="{x0}" y="22">{ttl}</text>')
# b: the folds
B = Ax(600, 50, 230, 230, (tt[0], tt[-1]), (0, 1.1))
sharp = p(tt)
sh = np.linspace(0, D, 401); smear = np.mean([p(tt - s) for s in sh], 0)
for v in (0.25, 0.5, 0.75, 1.0):
    o.append(f'<path class="grid" d="M{B.x0} {float(B.Y(v)):.1f} H{B.x0 + B.w}"/>')
o.append(B.frame(xticks=[-20, 0, 20, 40], yticks=[0, 0.5, 1], xlab='time in the turn [ms]', ylab='folded profile'))
o.append(f'<path class="s1" d="{B.path(tt, sharp)}"><title>with the predictor</title></path>')
o.append(f'<path class="s2" d="{B.path(tt, smear)}"><title>constant spin rate</title></path>')
o.append(f'<text class="sub" x="{float(B.X(2)) + 6:.1f}" y="{float(B.Y(1.0)) + 4:.1f}" style="fill:var(--series-1)">with the predictor</text>')
ks = int(np.argmax(smear))
o.append(f'<text class="sub" x="{float(B.X(tt[ks])) + 10:.1f}" y="{float(B.Y(smear[ks])) - 6:.1f}" style="fill:var(--series-2)">constant rate</text>')
o.append(f'<text class="ttl" x="600" y="22">b · the folded sub-int</text>')

svg = '''<figure class="scroll">
<svg class="wide" viewBox="0 0 860 330" role="img" aria-label="B0329+54's pulse within a 120 s sub-int with a Doppler factor of 1e-4: with a constant spin rate the pulse walks by 12 ms and the folded profile is smeared; with the predictor it stays in place and the fold is sharp">
  ''' + '\n  '.join(o) + '''
</svg>
<figcaption><b>Figure 7a.2.</b> B0329+54's pulse (five components) in one 120 s sub-int, while the Earth's orbit changes the arrival rate by 10⁻⁴. (a) One
row every 5 s, at the phase the fold assigns. With a constant spin rate the pulse walks by 12 ms, more than twice its 5 ms core; with the
predictor every row stays in place. (b) The fold, the average of the rows. The walk lowers its peak to ''' + f'{smear.max() * 100:.0f}' + ''' % and widens it. A J0437 sub-int
of 300 s would walk by five whole turns. Generated by <code>docs/tools/figures/gen_dopsmear.py</code>.</figcaption>
</figure>'''
open('dopsmear.svg', 'w').write(svg)
print('walk ms', D, 'smeared peak', smear.max())
